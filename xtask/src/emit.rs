//! Rust source emission. Output is formatted with rustfmt afterwards.

use std::collections::BTreeSet;
use std::fmt::Write;

use anyhow::{Result, bail};

use crate::names::snake;
use crate::ops::{Body, Op, PartKind, Response, Segment};
use crate::types::{Kind, Registry, StructDef};

pub const HEADER: &str = "// @generated by `cargo xtask codegen` from `spec/polarion-openapi.json`. Do not edit by hand.\n";

fn doc(out: &mut String, indent: &str, lines: &[String]) {
    for line in lines {
        if line.is_empty() {
            let _ = writeln!(out, "{indent}///");
        } else {
            let _ = writeln!(out, "{indent}/// {line}");
        }
    }
}

pub fn models(reg: &Registry) -> Result<String> {
    let aliases: BTreeSet<&str> = reg
        .structs
        .values()
        .filter_map(|s| match &s.kind {
            Kind::Attributes { alias, .. } => Some(alias.as_str()),
            Kind::Plain => None,
        })
        .collect();
    for name in reg.structs.keys() {
        if aliases.contains(name.as_str()) {
            bail!("generated struct `{name}` collides with a resource alias");
        }
    }

    let mut out = String::from(HEADER);
    out.push_str(
        "//! Typed attributes for every Polarion resource type, and the bodies of action endpoints.\n\
         //!\n\
         //! Each resource type has an attributes struct (`WorkItemAttributes`) and an alias for the\n\
         //! full resource (`WorkItem = Resource<WorkItemAttributes>`). All attribute fields are\n\
         //! optional so the same struct serves for reading, creating and partial updates; attributes\n\
         //! the spec does not describe, such as custom fields, are kept in `extra`.\n\n\
         #![allow(clippy::doc_lazy_continuation)]\n\n\
         use std::collections::BTreeMap;\n\n\
         use serde::{Deserialize, Serialize};\n\
         use serde_json::Value;\n\n\
         use crate::jsonapi::{Resource, ResourceKind, TextContent};\n\n",
    );
    for def in reg.structs.values() {
        emit_struct(&mut out, def)?;
    }
    Ok(out)
}

fn emit_struct(out: &mut String, def: &StructDef) -> Result<()> {
    let mut lines = Vec::new();
    match &def.kind {
        Kind::Attributes {
            resource_type,
            alias,
        } => {
            lines.push(format!(
                "Attributes of a `{resource_type}` resource ([`{alias}`])."
            ));
            if !def.doc.is_empty() {
                lines.push(String::new());
                lines.extend(def.doc.iter().cloned());
            }
            if !def.relationships.is_empty() {
                lines.push(String::new());
                lines.push("# Relationships".into());
                lines.push(String::new());
                for (name, rel) in &def.relationships {
                    let targets: Vec<String> =
                        rel.targets.iter().map(|t| format!("`{t}`")).collect();
                    let card = if rel.to_many { "to-many" } else { "to-one" };
                    let targets = if targets.is_empty() {
                        String::new()
                    } else {
                        format!(" → {}", targets.join(", "))
                    };
                    lines.push(format!("- `{name}` ({card}){targets}"));
                }
            }
        }
        Kind::Plain => {
            if def.doc.is_empty() {
                lines.push(format!("`{}`", def.name));
            } else {
                lines.extend(def.doc.iter().cloned());
            }
        }
    }
    doc(out, "", &lines);
    let _ = writeln!(
        out,
        "#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]"
    );
    let _ = writeln!(out, "pub struct {} {{", def.name);
    let mut idents = BTreeSet::new();
    for field in def.fields.values() {
        if field.ident == "extra" || !idents.insert(field.ident.clone()) {
            bail!("{}: field name collision on `{}`", def.name, field.ident);
        }
        doc(out, "    ", &field.doc);
        let rename = if field.ident != field.json {
            format!("rename = \"{}\", ", field.json)
        } else {
            String::new()
        };
        let ty = field.ty.rust();
        if field.required {
            let _ = writeln!(out, "    #[serde({rename}default)]");
            let _ = writeln!(out, "    pub {}: {ty},", field.ident);
        } else {
            let _ = writeln!(
                out,
                "    #[serde({rename}default, skip_serializing_if = \"Option::is_none\")]"
            );
            let _ = writeln!(out, "    pub {}: Option<{ty}>,", field.ident);
        }
    }
    let _ = writeln!(
        out,
        "    /// Members not described by the spec, e.g. custom fields."
    );
    let _ = writeln!(out, "    #[serde(flatten)]");
    let _ = writeln!(out, "    pub extra: BTreeMap<String, Value>,");
    let _ = writeln!(out, "}}\n");
    if let Kind::Attributes {
        resource_type,
        alias,
    } = &def.kind
    {
        let _ = writeln!(
            out,
            "impl ResourceKind for {} {{\n    const TYPE: &'static str = \"{resource_type}\";\n}}\n",
            def.name
        );
        let _ = writeln!(
            out,
            "/// A `{resource_type}` resource.\npub type {alias} = Resource<{}>;\n",
            def.name
        );
    }
    Ok(())
}

pub fn operations(ops: &[Op]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(
        "//! One method per operation of the Polarion REST API.\n\n\
         #![allow(clippy::too_many_arguments, clippy::doc_lazy_continuation, unused_imports)]\n\n\
         use reqwest::Method;\n\
         use reqwest::header::CONTENT_TYPE;\n\
         use reqwest::multipart::Form;\n\
         use serde_json::Value;\n\n\
         use crate::client::{Client, FilePart, json_part};\n\
         use crate::error::Result;\n\
         use crate::generated::models::*;\n\
         use crate::jsonapi::{DataRef, Envelope, ListEnvelope, RelationshipData, Resource, ResourceRef, SingleEnvelope};\n\
         use crate::query::Query;\n\n",
    );
    let mut current_tag: Option<&str> = None;
    for op in ops {
        if current_tag != Some(op.tag.as_str()) {
            if current_tag.is_some() {
                out.push_str("}\n\n");
            }
            let _ = writeln!(out, "/// # {}", op.tag);
            out.push_str("impl Client {\n");
            current_tag = Some(&op.tag);
        }
        emit_op(&mut out, op);
    }
    if current_tag.is_some() {
        out.push_str("}\n");
    }
    out
}

fn emit_op(out: &mut String, op: &Op) {
    doc(out, "    ", &op.doc);

    let mut args = vec!["&self".to_owned()];
    args.extend(op.path_params.iter().map(|p| format!("{p}: &str")));
    args.extend(op.required_query.iter().map(|(_, i)| format!("{i}: &str")));
    if !op.optional_query.is_empty() {
        args.push("query: &Query".into());
    }
    match &op.body {
        Body::None => {}
        Body::Json { ident, payload } => args.push(format!("{ident}: {}", payload.arg_type())),
        Body::Bytes => args.push("body: Vec<u8>".into()),
        Body::Multipart(parts) => {
            for part in parts {
                let ty = match (&part.kind, part.required) {
                    (PartKind::File, true) => "FilePart".to_owned(),
                    (PartKind::File, false) => "Option<FilePart>".to_owned(),
                    (PartKind::Files, _) => "Vec<FilePart>".to_owned(),
                    (PartKind::Json(p), true) => p.arg_type(),
                    (PartKind::Json(p), false) => format!("Option<{}>", p.arg_type()),
                };
                args.push(format!("{}: {ty}", part.ident));
            }
        }
    }
    let ret = match &op.response {
        Response::Unit => "()".to_owned(),
        Response::Bytes => "Vec<u8>".to_owned(),
        Response::Json(t) => t.clone(),
    };
    let _ = writeln!(
        out,
        "    pub async fn {}({}) -> Result<{ret}> {{",
        op.fn_name,
        args.join(", ")
    );

    // Query.
    let query_expr = if op.required_query.is_empty() {
        if op.optional_query.is_empty() {
            "None"
        } else {
            "Some(query)"
        }
    } else {
        let base = if op.optional_query.is_empty() {
            "Query::new()"
        } else {
            "query.clone()"
        };
        let mut expr = base.to_owned();
        for (json, ident) in &op.required_query {
            let _ = write!(expr, ".param({json:?}, {ident})");
        }
        let _ = writeln!(out, "        let query = {expr};");
        "Some(&query)"
    };

    let segments: Vec<String> = op
        .segments
        .iter()
        .map(|s| match s {
            Segment::Lit(l) => format!("{l:?}"),
            Segment::Param(p) => p.clone(),
        })
        .collect();
    let mutability = if matches!(op.body, Body::None) {
        ""
    } else {
        "mut "
    };
    let _ = writeln!(
        out,
        "        let {mutability}req = self.request(Method::{}, &[{}], {query_expr});",
        op.method,
        segments.join(", ")
    );

    match &op.body {
        Body::None => {}
        Body::Json { ident, payload } => {
            if payload.wrapped() {
                let field = if ident == "data" {
                    "data".to_owned()
                } else {
                    format!("data: {ident}")
                };
                let _ = writeln!(out, "        req = req.json(&DataRef {{ {field} }});");
            } else {
                let _ = writeln!(out, "        req = req.json({ident});");
            }
        }
        Body::Bytes => {
            let _ = writeln!(
                out,
                "        req = req.header(CONTENT_TYPE, \"application/octet-stream\").body(body);"
            );
        }
        Body::Multipart(parts) => {
            let _ = writeln!(out, "        let mut form = Form::new();");
            for part in parts {
                let (name, ident) = (&part.name, &part.ident);
                match (&part.kind, part.required) {
                    (PartKind::File, true) => {
                        let _ = writeln!(
                            out,
                            "        form = form.part({name:?}, {ident}.into_part()?);"
                        );
                    }
                    (PartKind::File, false) => {
                        let _ = writeln!(
                            out,
                            "        if let Some(file) = {ident} {{ form = form.part({name:?}, file.into_part()?); }}"
                        );
                    }
                    (PartKind::Files, _) => {
                        let _ = writeln!(
                            out,
                            "        for file in {ident} {{ form = form.part({name:?}, file.into_part()?); }}"
                        );
                    }
                    (PartKind::Json(p), required) => {
                        let value = if p.wrapped() {
                            "&DataRef { data: v }".to_owned()
                        } else {
                            "v".to_owned()
                        };
                        if required {
                            let _ = writeln!(out, "        let v = {ident};");
                            let _ = writeln!(
                                out,
                                "        form = form.part({name:?}, json_part({value})?);"
                            );
                        } else {
                            let _ = writeln!(
                                out,
                                "        if let Some(v) = {ident} {{ form = form.part({name:?}, json_part({value})?); }}"
                            );
                        }
                    }
                }
            }
            let _ = writeln!(out, "        req = req.multipart(form);");
        }
    }
    let exec = match &op.response {
        Response::Unit => "execute_empty",
        Response::Bytes => "execute_bytes",
        Response::Json(_) => "execute_json",
    };
    let _ = writeln!(out, "        self.{exec}(req).await");
    let _ = writeln!(out, "    }}\n");
}

/// One round-trip test per envelope and plain schema reachable from operations.
pub fn spec_tests(cases: &[(String, String)]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(
        "//! Every schema's example (synthesized from the spec) must round-trip through its Rust type.\n\n\
         mod support;\n\n\
         #[allow(unused_imports)]\n\
         use polarion_rest::models::*;\n\
         #[allow(unused_imports)]\n\
         use polarion_rest::{Envelope, ListEnvelope, RelationshipData, Resource, ResourceRef, SingleEnvelope};\n\n",
    );
    for (schema, ty) in cases {
        let _ = writeln!(
            out,
            "#[test]\nfn {}() {{\n    support::roundtrip::<{ty}>({schema:?});\n}}\n",
            snake(schema)
        );
    }
    out
}
