/// The declarations of a `style` attribute: lowercase names, trimmed values (keywords lowercase,
/// whitespace collapsed), `!important` removed.
fn declarations(style: &str) -> Vec<(String, String)> {
    style
        .split(';')
        .filter_map(|declaration| {
            let (property, value) = declaration.split_once(':')?;
            let property = property.trim().to_ascii_lowercase();
            let value = value.trim();
            let value = value
                .strip_suffix("!important")
                .unwrap_or(value)
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ");
            let value = if property == "font-family" {
                value
            } else {
                value.to_ascii_lowercase()
            };
            (!property.is_empty() && !value.is_empty()).then_some((property, value))
        })
        .collect()
}

fn align_of(value: &str) -> Option<Align> {
    match value.trim().to_ascii_lowercase().as_str() {
        "left" | "start" => Some(Align::Left),
        "center" | "middle" => Some(Align::Center),
        "right" | "end" => Some(Align::Right),
        "justify" => Some(Align::Justify),
        _ => None,
    }
}

/// A length in px (`px`, `pt`, `em` at 16px, unitless numbers); `None` for others.
fn length(value: &str) -> Option<i64> {
    let value = value.trim();
    let (number, factor) = if let Some(n) = value.strip_suffix("px") {
        (n, 1.0)
    } else if let Some(n) = value.strip_suffix("pt") {
        (n, 4.0 / 3.0)
    } else if let Some(n) = value.strip_suffix("em") {
        (n, 16.0)
    } else {
        (value, 1.0)
    };
    let number: f64 = number.trim().parse().ok()?;
    Some((number * factor).round() as i64)
}

/// The left value of a `margin` or `padding` shorthand (1 to 4 values).
fn shorthand_left(value: &str) -> Option<i64> {
    let parts: Vec<&str> = value.split_whitespace().collect();
    let left = match parts.len() {
        1 => parts[0],
        2 | 3 => parts[1],
        4 => parts[3],
        _ => return None,
    };
    length(left)
}

fn side_left(declarations: &[(String, String)], name: &str) -> i64 {
    let mut left = 0;
    for (property, value) in declarations {
        if property == name {
            left = shorthand_left(value).unwrap_or(left);
        } else if property == &format!("{name}-left") {
            left = length(value).unwrap_or(left);
        }
    }
    left
}

fn margin_left(declarations: &[(String, String)]) -> i64 {
    side_left(declarations, "margin")
}

fn padding_left(declarations: &[(String, String)]) -> i64 {
    side_left(declarations, "padding")
}

/// Width and colour of a visible `border` / `border-left` value.
fn border(value: &str) -> Option<(i64, String)> {
    let mut width = 3; // `medium`
    let mut color_value = "#000000".to_owned();
    let mut visible = false;
    for token in value.split_whitespace() {
        match token {
            "none" | "hidden" => return None,
            "solid" | "dashed" | "dotted" | "double" | "groove" | "ridge" | "inset" | "outset" => {
                visible = true;
            }
            "thin" => width = 1,
            "medium" => width = 3,
            "thick" => width = 5,
            t => match length(t) {
                Some(w) if t.chars().next().is_some_and(|c| c.is_ascii_digit()) => width = w,
                _ => color_value = color(t),
            },
        }
    }
    (visible && width > 0).then_some((width, color_value))
}

/// A font size in hundredths of a point (`pt`, `px`, `em` and `%` of the inherited size).
fn font_size(value: &str, inherited: Option<i64>) -> Option<i64> {
    let base = inherited.unwrap_or(1000) as f64;
    let value = value.trim();
    let (n, scale) = [
        ("pt", 100.0),
        ("px", 75.0),
        ("em", base),
        ("%", base / 100.0),
    ]
    .into_iter()
    .find_map(|(unit, scale)| value.strip_suffix(unit).map(|n| (n, scale)))?;
    Some((n.trim().parse::<f64>().ok()? * scale).round() as i64)
}

/// Monospace for any family list naming a monospace font, else the normalized list.
fn font(value: &str) -> Font {
    let families: Vec<String> = value
        .split(',')
        .map(|f| {
            f.trim()
                .trim_matches(|c| c == '\'' || c == '"')
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
                .to_ascii_lowercase()
        })
        .filter(|f| !f.is_empty())
        .collect();
    const MONOSPACE: &[&str] = &[
        "monospace",
        "courier",
        "courier new",
        "consolas",
        "menlo",
        "monaco",
        "lucida console",
        "dejavu sans mono",
        "source code pro",
    ];
    if families.iter().any(|f| MONOSPACE.contains(&f.as_str())) {
        Font::Mono
    } else {
        Font::Family(families.join(","))
    }
}

/// A colour as `#rrggbb` where it can be (hex, `rgb()`, common names), else as written.
fn color(value: &str) -> String {
    let value = value.trim().to_ascii_lowercase();
    if let Some(hex) = value.strip_prefix('#') {
        if hex.len() == 3 && hex.chars().all(|c| c.is_ascii_hexdigit()) {
            let doubled: String = hex.chars().flat_map(|c| [c, c]).collect();
            return format!("#{doubled}");
        }
        return value;
    }
    if let Some(inner) = value
        .strip_prefix("rgb(")
        .or_else(|| value.strip_prefix("rgba("))
        .and_then(|v| v.strip_suffix(')'))
    {
        let parts: Vec<&str> = inner
            .split([',', ' ', '/'])
            .filter(|p| !p.is_empty())
            .collect();
        let channel = |p: &str| {
            p.trim()
                .parse::<f64>()
                .ok()
                .map(|v| v.clamp(0.0, 255.0) as u8)
        };
        if parts.len() >= 3
            && parts.get(3).is_none_or(|a| a.trim() == "1")
            && let (Some(r), Some(g), Some(b)) =
                (channel(parts[0]), channel(parts[1]), channel(parts[2]))
        {
            return format!("#{r:02x}{g:02x}{b:02x}");
        }
        return value;
    }
    const NAMES: &[(&str, &str)] = &[
        ("aqua", "#00ffff"),
        ("black", "#000000"),
        ("blue", "#0000ff"),
        ("cyan", "#00ffff"),
        ("darkblue", "#00008b"),
        ("darkcyan", "#008b8b"),
        ("darkgreen", "#006400"),
        ("darkred", "#8b0000"),
        ("fuchsia", "#ff00ff"),
        ("gray", "#808080"),
        ("green", "#008000"),
        ("grey", "#808080"),
        ("lime", "#00ff00"),
        ("magenta", "#ff00ff"),
        ("maroon", "#800000"),
        ("navy", "#000080"),
        ("olive", "#808000"),
        ("orange", "#ffa500"),
        ("purple", "#800080"),
        ("red", "#ff0000"),
        ("silver", "#c0c0c0"),
        ("teal", "#008080"),
        ("white", "#ffffff"),
        ("yellow", "#ffff00"),
    ];
    NAMES
        .iter()
        .find(|(name, _)| *name == value)
        .map_or(value.clone(), |(_, hex)| (*hex).to_owned())
}

/// The colour of a `background` / `background-color` value; `None` for none or transparent.
fn background_color(value: &str) -> Option<String> {
    let value = value.trim();
    if value.is_empty()
        || matches!(
            value,
            "none" | "transparent" | "inherit" | "initial" | "unset" | "rgba(0, 0, 0, 0)"
        )
    {
        return None;
    }
    // The colour is the first value of a `background` shorthand; `rgb(…)` contains spaces.
    let first = match value.find(')') {
        Some(end) if value.starts_with("rgb") => &value[..=end],
        _ => value.split_whitespace().next().unwrap_or(value),
    };
    Some(color(first))
}

fn image(el: &ElementRef<'_>, declarations: &[(String, String)]) -> Object {
    let attr = |name: &str| {
        el.value()
            .attr(name)
            .map(str::to_owned)
            .filter(|v| !v.is_empty())
    };
    let src = attr("src").unwrap_or_default().trim().to_owned();
    if let Some(source) = mermaid_ink_source(&src) {
        return Object::Diagram(diagram_source(&source));
    }
    let size = |name: &str| {
        declarations
            .iter()
            .rev()
            .find(|(p, _)| p == name)
            .and_then(|(_, v)| length(v))
            .or_else(|| attr(name).and_then(|v| length(&v)))
            .map(|px| format!("{px}px"))
    };
    Object::Image {
        src,
        title: attr("title"),
        alt: attr("alt"),
        width: size("width"),
        height: size("height"),
    }
}

/// The `data-*` attributes of an element, sorted by name.
fn data_attributes(el: &ElementRef<'_>) -> Vec<(String, String)> {
    let mut attributes: Vec<(String, String)> = el
        .value()
        .attrs()
        .filter(|(name, _)| name.starts_with("data-"))
        .map(|(name, value)| (name.to_ascii_lowercase(), value.to_owned()))
        .collect();
    attributes.sort();
    attributes
}

/// The source of a formula: `<br>` written in it is a line break, edge whitespace is not
/// rendered.
fn formula_source(source: &str) -> String {
    let mut out = source.replace("\r\n", "\n");
    for br in ["<br/>", "<br />", "<br>", "<BR/>", "<BR />", "<BR>"] {
        out = out.replace(br, "\n");
    }
    out.trim().to_owned()
}

/// The work item id an anchor links to when its label is that id (or empty).
fn work_item_anchor(el: &ElementRef<'_>) -> Option<String> {
    let href = el.value().attr("href")?;
    let start = href.find("workitem?id=")? + "workitem?id=".len();
    let id: String = href[start..]
        .chars()
        .take_while(|&c| c != '&' && c != '#')
        .collect();
    let (key, number) = id.split_once('-')?;
    let shaped = key.chars().next().is_some_and(|c| c.is_ascii_alphabetic())
        && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !number.is_empty()
        && number.chars().all(|c| c.is_ascii_digit());
    let label: String = el.text().collect();
    let label = label.trim();
    (shaped && (label.is_empty() || label == id)).then_some(id)
}

fn pre_text(el: ElementRef<'_>, out: &mut String) {
    for child in el.children() {
        match child.value() {
            Node::Text(text) => out.push_str(&text.text),
            Node::Element(element) => {
                let name = element.name().to_ascii_lowercase();
                if name == "br" {
                    out.push('\n');
                } else if !HIDDEN.contains(&name.as_str())
                    && let Some(child) = ElementRef::wrap(child)
                {
                    pre_text(child, out);
                }
            }
            _ => {}
        }
    }
}

fn is_mermaid_pre(el: &ElementRef<'_>) -> bool {
    let names_mermaid = |e: &ElementRef<'_>| {
        e.value().classes().any(|c| {
            let c = c.to_ascii_lowercase();
            c == "language-mermaid" || c == "lang-mermaid" || c == "mermaid"
        }) || ["data-lang", "data-language"].iter().any(|a| {
            e.value()
                .attr(a)
                .is_some_and(|v| v.trim().eq_ignore_ascii_case("mermaid"))
        })
    };
    names_mermaid(el)
        || el
            .child_elements()
            .any(|c| c.value().name().eq_ignore_ascii_case("code") && names_mermaid(&c))
}

/// A diagram source compared by its lines: line ends unified, trailing spaces and leading and
/// trailing empty lines removed.
fn diagram_source(source: &str) -> String {
    let unified = source.replace("\r\n", "\n").replace('\r', "\n");
    let lines: Vec<&str> = unified.split('\n').map(str::trim_end).collect();
    let first = lines.iter().position(|l| !l.is_empty());
    let last = lines.iter().rposition(|l| !l.is_empty());
    match (first, last) {
        (Some(first), Some(last)) => lines[first..=last].join("\n"),
        _ => String::new(),
    }
}

/// The source in a legacy `https://mermaid.ink/img/…` or `…/svg/…` URL: standard or URL-safe
/// base64 of the source, or of a JSON object whose `code` is the source.
fn mermaid_ink_source(src: &str) -> Option<String> {
    use base64::Engine as _;
    use base64::engine::general_purpose::{STANDARD_PAD_INDIFFERENT, URL_SAFE_PAD_INDIFFERENT};

    let rest = src
        .strip_prefix("https://mermaid.ink/img/")
        .or_else(|| src.strip_prefix("https://mermaid.ink/svg/"))?;
    let payload = rest.split(['?', '#']).next()?;
    let bytes = STANDARD_PAD_INDIFFERENT
        .decode(payload)
        .or_else(|_| URL_SAFE_PAD_INDIFFERENT.decode(payload))
        .ok()?;
    let text = String::from_utf8(bytes).ok()?;
    if let Ok(serde_json::Value::Object(object)) = serde_json::from_str(&text)
        && let Some(serde_json::Value::String(code)) = object.get("code")
    {
        return Some(code.clone());
    }
    Some(text)
}

