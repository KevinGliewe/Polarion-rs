//! What a reader sees of Polarion rich text: an HTML fragment as a canonical list of rows (lines
//! of styled text, blank space, rules, tables, diagrams), to check that converting HTML to
//! Markdown and back keeps the visible result.
//!
//! The model is built with scraper alone and shares nothing with the crate under test, so it
//! catches the crate's mistakes instead of repeating them. It follows how a browser lays out the
//! HTML:
//! - **Blocks and lines.** Block elements (`div`, `p`, lists, tables, `pre`, `hr`, ...) start and
//!   end lines. Inside a block, every `<br>` ends a line (an empty one is a blank line); content
//!   after the last `<br>` is a line only when it is not empty, so a `<br>` just before a block or
//!   at the end of a container shows nothing. Unknown elements are inline.
//! - **Whitespace.** Runs of spaces, tabs and line breaks collapse to one space, and spaces at the
//!   start and end of a line disappear (`pre` keeps them, except at the end). A no-break space
//!   does not collapse and is then compared as a space: what it looks like, not how it is stored.
//!   Whitespace has no style of its own (a bold space looks like a plain one, and conversions move
//!   spaces in and out of emphasis).
//! - **Text style**, per run, as CSS computes it: bold, italic, underline and line-through (which
//!   descendants cannot remove), superscript, subscript, monospace or another font family, size
//!   (10pt is Polarion's default), colour, background of inline elements (any spelling of yellow
//!   is the same highlight), link target and title, and every other declaration of an inline
//!   element's `style`. Element defaults count (`b`, `em`, `u`, `s`, `mark`, `code`, `sup`, `th`,
//!   ...); `<br>` and `<br/>`, attribute order and style spelling (spaces, a trailing `;`, case,
//!   `&#39;` or `'`) do not matter.
//! - **Line context**: the left offset (margins, paddings and left borders of the enclosing
//!   blocks, 40px per list level), the colours of left borders (alerts), the alignment and the
//!   list markers drawn on the line.
//! - **Objects**: images (source, title, alt text, width, height), Polarion formulas (source,
//!   display or inline), Polarion links (every `data-*` attribute), mermaid diagrams (source).
//!
//! Ignored on purpose, each a difference the conversion makes and a reader does not see or does
//! not care about:
//! - Table, row and cell CSS other than alignment and cell background (borders, widths, padding,
//!   heights, vertical alignment): the conversion rewrites tables in Polarion's standard style.
//!   Table structure (rows, cells, colspan, rowspan) is compared.
//! - `line-height`: heading spans are written with the editor's line heights.
//! - An image's `max-width`, `class` and `data-*` attributes: every image is written with
//!   `max-width: 650px` and without `data-lastmodified`.
//! - Inside `pre`, everything but the text: highlighting is regenerated by the conversion. A
//!   `pre` is always indented by 40px, the editor's code style, whatever its own margin says.
//! - Backgrounds of block elements other than cells (a highlighter's white wrapper `div`).
//! - Tooltips (`title`) of elements other than links and images; `id` and `class` attributes.
//! - Elements that are not displayed in Polarion rich text: scripts, styles, embedded frames and
//!   objects, form controls, `display: none`, comments.
//! - Vertical margins as amounts: a margin of a `p`, `pre`, top-level list, `hr`, `blockquote`
//!   or heading element shows as one blank line, and one blank line made of `<br>`s next to such
//!   a margin merges into it (browsers and Polarion's stylesheet differ in how much space a margin
//!   takes, and the editor relies on them). Margins at the start or end of a container, and blank
//!   lines at the end of the document, are not shown.
//!
//! Three equivalences stand for changes the conversion makes on purpose:
//! - A heading-like line (all text at least 14pt, or larger than 10pt and bold) is compared by its
//!   heading level (smallest size: ≥22 → 1, ≥18 → 2, ≥14 → 3, ≥12 → 4, ≥11 → 5, else 6) instead of
//!   its exact size and weight: such lines become Markdown headings, written in the six heading
//!   sizes.
//! - A link to a work item URL (`…workitem?id=ID`) labelled with the id (or empty) is the long
//!   work item link to that id.
//! - A mermaid diagram is its source, whether it is shown as a code block (`pre` of language
//!   mermaid) or as an image of a legacy mermaid.ink URL (base64 of the source).

#![allow(dead_code)]

use std::fmt::Write as _;

use scraper::{CaseSensitivity, ElementRef, Html, Node};

/// The visual model of an HTML fragment, one row per line of the dump. The model is built
/// recursively, on a thread with a large stack: deeply nested input must not overflow the stack
/// of the calling test.
pub fn render(html: &str) -> String {
    let html = html.to_owned();
    std::thread::Builder::new()
        .stack_size(256 << 20)
        .spawn(move || render_here(&html))
        .expect("a thread for the visual model")
        .join()
        .unwrap_or_else(|panic| std::panic::resume_unwind(panic))
}

fn render_here(html: &str) -> String {
    let document = Html::parse_fragment(html);
    let mut builder = Builder::default();
    let ctx = Ctx::default();
    builder.children(document.root_element(), &ctx);
    builder.flush();
    let rows = finish(builder.rows, Edge::Document);
    let mut out = String::new();
    dump(&rows, 0, &mut out);
    out
}

/// Panics, naming the first row that differs, unless `actual` looks like `expected`.
pub fn assert_same(context: &str, expected: &str, actual: &str) {
    if let Some(message) = difference(expected, actual) {
        panic!("{context}: the HTML does not look the same\n{message}");
    }
}

/// `None` if `actual` looks like `expected`, else a description of the first differing row.
pub fn difference(expected: &str, actual: &str) -> Option<String> {
    let (want, got) = (render(expected), render(actual));
    if want == got {
        return None;
    }
    let want_lines: Vec<&str> = want.lines().collect();
    let got_lines: Vec<&str> = got.lines().collect();
    let first = (0..want_lines.len().max(got_lines.len()))
        .find(|&i| want_lines.get(i) != got_lines.get(i))
        .unwrap_or(0);
    let from = first.saturating_sub(3);
    let mut message = format!("first difference in row {}:\n", first + 1);
    let _ = writeln!(
        message,
        "  expected: {}\n  actual:   {}",
        want_lines.get(first).unwrap_or(&"<end>"),
        got_lines.get(first).unwrap_or(&"<end>")
    );
    let _ = writeln!(message, "rows before it:");
    for line in &want_lines[from.min(want_lines.len())..first.min(want_lines.len())] {
        let _ = writeln!(message, "  {line}");
    }
    let _ = writeln!(message, "expected model:\n{want}\nactual model:\n{got}");
    Some(message)
}

