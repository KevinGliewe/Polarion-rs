#[derive(Debug, Clone, Default, PartialEq)]
struct Style {
    bold: bool,
    italic: bool,
    underline: bool,
    strike: bool,
    vertical: Vertical,
    font: Option<Font>,
    /// Hundredths of a point; `None` is the default size (10pt).
    size: Option<i64>,
    color: Option<String>,
    background: Option<String>,
    link: Option<Link>,
    /// Other declarations of inline elements, `name: value`, sorted.
    extra: Vec<String>,
}

#[derive(Debug, Clone, Copy, Default, PartialEq)]
enum Vertical {
    #[default]
    Baseline,
    Super,
    Sub,
}

#[derive(Debug, Clone, PartialEq)]
enum Font {
    Mono,
    Family(String),
}

#[derive(Debug, Clone, PartialEq)]
struct Link {
    href: String,
    title: Option<String>,
}

#[derive(Debug, Clone, Copy, Default, PartialEq)]
enum Align {
    #[default]
    Left,
    Center,
    Right,
    Justify,
}

#[derive(Debug, Clone, Default, PartialEq)]
struct LineCtx {
    indent: i64,
    align: Align,
    bars: Vec<String>,
}

#[derive(Debug, Clone, PartialEq)]
enum Object {
    Image {
        src: String,
        title: Option<String>,
        alt: Option<String>,
        width: Option<String>,
        height: Option<String>,
    },
    Formula {
        source: String,
        display: bool,
    },
    /// A Polarion link: its `data-*` attributes, sorted.
    PolarionLink(Vec<(String, String)>),
    Diagram(String),
}

