fn class(el: &ElementRef<'_>, name: &str) -> bool {
    el.value()
        .has_class(name, CaseSensitivity::AsciiCaseInsensitive)
}

impl Builder {
    fn children(&mut self, el: ElementRef<'_>, ctx: &Ctx) {
        for child in el.children() {
            match child.value() {
                Node::Text(text) => self.text(&text.text, ctx),
                Node::Element(_) => {
                    if let Some(child) = ElementRef::wrap(child) {
                        self.element(child, ctx);
                    }
                }
                _ => {}
            }
        }
    }

    fn text(&mut self, text: &str, ctx: &Ctx) {
        for c in text.chars() {
            let space = matches!(c, ' ' | '\t' | '\n' | '\r' | '\u{c}');
            self.atoms.push(Atom::Char {
                c: if space { ' ' } else { c },
                style: ctx.style.clone(),
                space,
            });
        }
    }

    fn element(&mut self, el: ElementRef<'_>, ctx: &Ctx) {
        let name = el.value().name().to_ascii_lowercase();
        let declarations = declarations(el.value().attr("style").unwrap_or(""));
        if HIDDEN.contains(&name.as_str())
            || declarations
                .iter()
                .any(|(p, v)| p == "display" && v == "none")
        {
            return;
        }
        match name.as_str() {
            "br" => {
                self.atoms.push(Atom::Br);
                return;
            }
            "img" => {
                let object = image(&el, &declarations);
                self.atoms.push(Atom::Object(object, ctx.style.clone()));
                return;
            }
            "span" if class(&el, "polarion-rte-link") => {
                self.atoms.push(Atom::Object(
                    Object::PolarionLink(data_attributes(&el)),
                    ctx.style.clone(),
                ));
                return;
            }
            "span" if class(&el, "polarion-rte-formula") => {
                let object = Object::Formula {
                    source: formula_source(el.value().attr("data-source").unwrap_or("")),
                    display: el
                        .value()
                        .attr("data-inline")
                        .is_some_and(|v| v.trim().eq_ignore_ascii_case("false")),
                };
                self.atoms.push(Atom::Object(object, ctx.style.clone()));
                return;
            }
            "a" => {
                if let Some(id) = work_item_anchor(&el) {
                    let attributes = vec![
                        ("data-item-id".to_owned(), id),
                        ("data-option-id".to_owned(), "long".to_owned()),
                        ("data-type".to_owned(), "workItem".to_owned()),
                    ];
                    self.atoms.push(Atom::Object(
                        Object::PolarionLink(attributes),
                        ctx.style.clone(),
                    ));
                    return;
                }
            }
            _ => {}
        }
        let block = BLOCKS.contains(&name.as_str());
        let child = child_ctx(&el, &name, &declarations, ctx, block);
        if !block {
            self.children(el, &child);
            return;
        }
        match name.as_str() {
            "table" => self.table(el, &child),
            "pre" | "listing" => self.pre(el, &child),
            "hr" => {
                self.flush();
                self.rows.push(Row::Gap);
                self.rows.push(Row::Rule {
                    indent: child.line.indent,
                });
                self.rows.push(Row::Gap);
            }
            "ul" | "ol" | "menu" | "dir" => self.list(el, &name, &child, ctx),
            _ => {
                let margins = MARGINS.contains(&name.as_str());
                self.block(el, &child, margins);
            }
        }
    }

    /// A block: its own lines, with the margins of `margins` elements around them.
    fn block(&mut self, el: ElementRef<'_>, ctx: &Ctx, margins: bool) {
        self.flush();
        if margins {
            self.rows.push(Row::Gap);
        }
        let outer = std::mem::replace(&mut self.line, ctx.line.clone());
        self.children(el, ctx);
        self.flush();
        self.line = outer;
        if margins {
            self.rows.push(Row::Gap);
        }
    }

    fn list(&mut self, el: ElementRef<'_>, name: &str, ctx: &Ctx, outer: &Ctx) {
        // Lists inside lists have no vertical margins.
        let margins = outer.lists == 0;
        self.flush();
        if margins {
            self.rows.push(Row::Gap);
        }
        let mut ctx = ctx.clone();
        ctx.line.indent += 40;
        ctx.lists += 1;
        let ordered = name == "ol";
        let mut number: i64 = el
            .value()
            .attr("start")
            .and_then(|s| s.trim().parse().ok())
            .unwrap_or(1);
        let outer_line = std::mem::replace(&mut self.line, ctx.line.clone());
        for child in el.children() {
            match child.value() {
                Node::Text(text) => self.text(&text.text, &ctx),
                Node::Element(_) => {
                    let Some(child) = ElementRef::wrap(child) else {
                        continue;
                    };
                    if child.value().name().eq_ignore_ascii_case("li") {
                        self.flush();
                        let marker = if ordered {
                            format!("{number}.")
                        } else {
                            ["disc", "circle", "square"][(ctx.lists - 1).min(2)].to_owned()
                        };
                        number += 1;
                        self.markers.push(marker);
                        self.element(child, &ctx);
                        self.flush();
                        if !self.markers.is_empty() {
                            // An empty item still shows its marker.
                            self.rows.push(Row::Line(Line {
                                ctx: ctx.line.clone(),
                                markers: std::mem::take(&mut self.markers),
                                heading: None,
                                items: Vec::new(),
                            }));
                        }
                    } else {
                        self.element(child, &ctx);
                    }
                }
                _ => {}
            }
        }
        self.flush();
        self.line = outer_line;
        if margins {
            self.rows.push(Row::Gap);
        }
    }

    /// A `pre`: its text in monospace, whitespace kept, `<br>` and line breaks ending lines; a
    /// mermaid block is its diagram.
    fn pre(&mut self, el: ElementRef<'_>, ctx: &Ctx) {
        self.flush();
        self.rows.push(Row::Gap);
        let mut text = String::new();
        pre_text(el, &mut text);
        if is_mermaid_pre(&el) {
            self.rows.push(Row::Diagram {
                indent: self.line.indent,
                source: diagram_source(&text),
            });
            self.rows.push(Row::Gap);
            return;
        }
        let mut lines: Vec<&str> = text.split('\n').collect();
        if lines.last() == Some(&"") {
            lines.pop();
        }
        // The pre's own margin is the editor's code indentation, 40px.
        let own = margin_left(&declarations(el.value().attr("style").unwrap_or("")));
        let mut line_ctx = ctx.line.clone();
        line_ctx.indent = line_ctx.indent - own + 40;
        for line in lines {
            let mut pieces: Vec<(char, Style)> = Vec::new();
            for c in line.chars() {
                let style = if c.is_whitespace() || c == '\u{a0}' {
                    Style::default()
                } else {
                    Style {
                        font: Some(Font::Mono),
                        ..Style::default()
                    }
                };
                pieces.push((if c == '\u{a0}' { ' ' } else { c }, style));
            }
            while pieces.last().is_some_and(|(c, _)| c.is_whitespace()) {
                pieces.pop();
            }
            if pieces.is_empty() && self.markers.is_empty() {
                self.rows.push(Row::Blank);
                continue;
            }
            self.rows.push(Row::Line(Line {
                ctx: line_ctx.clone(),
                markers: std::mem::take(&mut self.markers),
                heading: None,
                items: group(pieces.into_iter().map(Piece::Char).collect()),
            }));
        }
        self.rows.push(Row::Gap);
    }

    fn table(&mut self, el: ElementRef<'_>, ctx: &Ctx) {
        self.flush();
        if !self.markers.is_empty() {
            self.rows.push(Row::Line(Line {
                ctx: self.line.clone(),
                markers: std::mem::take(&mut self.markers),
                heading: None,
                items: Vec::new(),
            }));
        }
        let mut rows = Vec::new();
        collect_rows(el, ctx, &mut rows);
        self.rows.push(Row::Table {
            indent: ctx.line.indent,
            rows,
        });
    }

    /// The pending inline content as lines: split at each `<br>`, whitespace collapsed.
    fn flush(&mut self) {
        let atoms = std::mem::take(&mut self.atoms);
        let mut segments: Vec<Vec<Atom>> = vec![Vec::new()];
        for atom in atoms {
            match atom {
                Atom::Br => segments.push(Vec::new()),
                atom => {
                    if let Some(segment) = segments.last_mut() {
                        segment.push(atom);
                    }
                }
            }
        }
        let count = segments.len();
        for (i, segment) in segments.into_iter().enumerate() {
            let last = i + 1 == count;
            let items = line_items(segment);
            if items.is_empty() {
                if last {
                    continue;
                }
                if self.markers.is_empty() {
                    self.rows.push(Row::Blank);
                    continue;
                }
            }
            let (heading, items) = heading_line(items);
            self.rows.push(Row::Line(Line {
                ctx: self.line.clone(),
                markers: std::mem::take(&mut self.markers),
                heading,
                items,
            }));
        }
    }
}

fn collect_rows(el: ElementRef<'_>, ctx: &Ctx, rows: &mut Vec<Vec<Cell>>) {
    for child in el.child_elements() {
        let name = child.value().name().to_ascii_lowercase();
        match name.as_str() {
            "thead" | "tbody" | "tfoot" => collect_rows(child, ctx, rows),
            "tr" => {
                let mut cells = Vec::new();
                for cell in child.child_elements() {
                    let cell_name = cell.value().name().to_ascii_lowercase();
                    if cell_name == "td" || cell_name == "th" {
                        cells.push(table_cell(cell, &cell_name, ctx));
                    }
                }
                rows.push(cells);
            }
            _ => {}
        }
    }
}

fn table_cell(el: ElementRef<'_>, name: &str, table: &Ctx) -> Cell {
    let declarations = declarations(el.value().attr("style").unwrap_or(""));
    let mut ctx = Ctx {
        style: table.style.clone(),
        line: LineCtx {
            indent: 0,
            align: table.line.align,
            bars: Vec::new(),
        },
        lists: 0,
    };
    if name == "th" {
        ctx.style.bold = true;
        ctx.line.align = Align::Center;
    }
    if let Some(align) = el.value().attr("align").and_then(align_of) {
        ctx.line.align = align;
    }
    let mut background = el.value().attr("bgcolor").map(color);
    for (property, value) in &declarations {
        match property.as_str() {
            "text-align" => {
                if let Some(align) = align_of(value) {
                    ctx.line.align = align;
                }
            }
            "background-color" | "background" => background = background_color(value),
            _ => text_declaration(&mut ctx.style, property, value, false),
        }
    }
    let span = |attr: &str| {
        el.value()
            .attr(attr)
            .and_then(|v| v.trim().parse::<u32>().ok())
            .filter(|&n| n > 0)
            .unwrap_or(1)
    };
    let mut builder = Builder {
        line: ctx.line.clone(),
        ..Builder::default()
    };
    builder.children(el, &ctx);
    builder.flush();
    Cell {
        colspan: span("colspan"),
        rowspan: span("rowspan"),
        background,
        rows: finish(builder.rows, Edge::Cell),
    }
}

/// The context of an element's content.
fn child_ctx(
    el: &ElementRef<'_>,
    name: &str,
    declarations: &[(String, String)],
    ctx: &Ctx,
    block: bool,
) -> Ctx {
    let mut child = ctx.clone();
    let style = &mut child.style;
    match name {
        "b" | "strong" => style.bold = true,
        "i" | "em" | "cite" | "var" | "dfn" | "address" => style.italic = true,
        "u" | "ins" => style.underline = true,
        "s" | "strike" | "del" => style.strike = true,
        "mark" => style.background = Some("#ffff00".to_owned()),
        "code" | "tt" | "kbd" | "samp" => style.font = Some(Font::Mono),
        "sup" => style.vertical = Vertical::Super,
        "sub" => style.vertical = Vertical::Sub,
        // Headings: bold, at the sizes Polarion's headings have (a heading line is compared by
        // its level).
        "h1" | "h2" | "h3" | "h4" | "h5" | "h6" => {
            style.bold = true;
            style.size =
                Some([2200, 1800, 1400, 1200, 1100, 1050][usize::from(name.as_bytes()[1] - b'1')]);
        }
        "th" | "dt" => style.bold = true,
        "font" => {
            if let Some(c) = el.value().attr("color") {
                style.color = Some(color(c));
            }
            if let Some(face) = el.value().attr("face") {
                style.font = Some(font(face));
            }
        }
        "a" => {
            if let Some(href) = el.value().attr("href") {
                style.link = Some(Link {
                    href: href.trim().to_owned(),
                    title: el
                        .value()
                        .attr("title")
                        .map(str::to_owned)
                        .filter(|t| !t.is_empty()),
                });
            }
        }
        "center" => child.line.align = Align::Center,
        "blockquote" | "dd" | "figure" => child.line.indent += 40,
        _ => {}
    }
    if block {
        if let Some(align) = el.value().attr("align").and_then(align_of) {
            child.line.align = align;
        }
        // Table borders and spacing are not compared (see the module documentation).
        let table = matches!(name, "table" | "thead" | "tbody" | "tfoot" | "tr");
        let mut indent = 0;
        for (property, value) in declarations {
            match property.as_str() {
                "text-align" => {
                    if let Some(align) = align_of(value) {
                        child.line.align = align;
                    }
                }
                "border-left" | "border" if !table => {
                    if let Some((width, color)) = border(value) {
                        indent += width;
                        child.line.bars.push(color);
                    }
                }
                _ => text_declaration(&mut child.style, property, value, false),
            }
        }
        if !table {
            indent += margin_left(declarations) + padding_left(declarations);
        }
        child.line.indent += indent;
    } else {
        for (property, value) in declarations {
            text_declaration(&mut child.style, property, value, true);
        }
        child.style.extra.sort();
    }
    child
}

/// Applies one declaration that styles text; `inline`: the element is inline (its background and
/// unknown declarations belong to its text).
fn text_declaration(style: &mut Style, property: &str, value: &str, inline: bool) {
    match property {
        "font-weight" => match value {
            "bold" | "bolder" => style.bold = true,
            "normal" | "lighter" => style.bold = false,
            v => {
                if let Ok(n) = v.parse::<u32>() {
                    style.bold = n >= 600;
                }
            }
        },
        "font-style" => match value {
            "italic" | "oblique" => style.italic = true,
            "normal" => style.italic = false,
            _ => {}
        },
        "text-decoration" | "text-decoration-line" => {
            for token in value.split_whitespace() {
                match token {
                    "underline" => style.underline = true,
                    "line-through" => style.strike = true,
                    _ => {}
                }
            }
        }
        "font-family" => style.font = Some(font(value)),
        "font-size" => {
            if let Some(size) = font_size(value, style.size) {
                style.size = (size != 1000).then_some(size);
            }
        }
        "color" => style.color = Some(color(value)),
        "vertical-align" => match value {
            "super" => style.vertical = Vertical::Super,
            "sub" => style.vertical = Vertical::Sub,
            "baseline" => style.vertical = Vertical::Baseline,
            _ => {}
        },
        "background-color" | "background" if inline => {
            style.background = background_color(value);
        }
        // Spacing, layout and properties of blocks.
        "line-height" | "display" | "background-color" | "background" | "text-align" | "width"
        | "height" | "max-width" | "min-width" | "max-height" | "min-height" | "white-space" => {}
        p if p.starts_with("margin")
            || p.starts_with("padding")
            || p.starts_with("border")
            || p.starts_with("list-style") => {}
        p if inline => {
            // The innermost declaration of a property wins.
            let prefix = format!("{p}: ");
            style.extra.retain(|e| !e.starts_with(&prefix));
            style.extra.push(format!("{p}: {value}"));
        }
        _ => {}
    }
}

