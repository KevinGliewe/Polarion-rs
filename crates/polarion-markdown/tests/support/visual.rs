fn dump(rows: &[Row], depth: usize, out: &mut String) {
    let pad = "  ".repeat(depth);
    for row in rows {
        match row {
            Row::Line(line) => {
                out.push_str(&pad);
                out.push_str("line");
                if line.ctx.indent != 0 {
                    let _ = write!(out, " indent={}", line.ctx.indent);
                }
                if line.ctx.align != Align::Left {
                    let _ = write!(out, " align={:?}", line.ctx.align);
                }
                if !line.ctx.bars.is_empty() {
                    let _ = write!(out, " bars={}", line.ctx.bars.join(","));
                }
                if !line.markers.is_empty() {
                    let _ = write!(out, " marker={}", line.markers.join("+"));
                }
                if let Some(level) = line.heading {
                    let _ = write!(out, " heading={level}");
                }
                out.push(':');
                for item in &line.items {
                    out.push(' ');
                    dump_item(item, out);
                }
                out.push('\n');
            }
            Row::Space(n) => {
                let _ = writeln!(out, "{pad}space {n}");
            }
            Row::Blank | Row::Gap => {
                let _ = writeln!(out, "{pad}{row:?}");
            }
            Row::Rule { indent } => {
                let _ = writeln!(out, "{pad}rule indent={indent}");
            }
            Row::Diagram { indent, source } => {
                let _ = writeln!(out, "{pad}diagram indent={indent}: {source:?}");
            }
            Row::Table { indent, rows } => {
                let _ = writeln!(out, "{pad}table indent={indent}");
                for cells in rows {
                    let _ = writeln!(out, "{pad}  row");
                    for cell in cells {
                        let _ = write!(out, "{pad}    cell");
                        if cell.colspan != 1 {
                            let _ = write!(out, " colspan={}", cell.colspan);
                        }
                        if cell.rowspan != 1 {
                            let _ = write!(out, " rowspan={}", cell.rowspan);
                        }
                        if let Some(background) = &cell.background {
                            let _ = write!(out, " background={background}");
                        }
                        out.push('\n');
                        dump(&cell.rows, depth + 3, out);
                    }
                }
            }
        }
    }
}

fn dump_item(item: &Item, out: &mut String) {
    match &item.kind {
        ItemKind::Text(text) => {
            let _ = write!(out, "{text:?}");
            dump_style(&item.style, out);
        }
        ItemKind::Object(object) => {
            match object {
                Object::Image {
                    src,
                    title,
                    alt,
                    width,
                    height,
                } => {
                    let _ = write!(out, "[image {src:?}");
                    if let Some(title) = title {
                        let _ = write!(out, " title={title:?}");
                    }
                    if let Some(alt) = alt {
                        let _ = write!(out, " alt={alt:?}");
                    }
                    if let Some(width) = width {
                        let _ = write!(out, " width={width}");
                    }
                    if let Some(height) = height {
                        let _ = write!(out, " height={height}");
                    }
                    out.push(']');
                }
                Object::Formula { source, display } => {
                    let kind = if *display { "display " } else { "" };
                    let _ = write!(out, "[{kind}formula {source:?}]");
                }
                Object::PolarionLink(attributes) => {
                    out.push_str("[polarion link");
                    for (name, value) in attributes {
                        let _ = write!(out, " {name}={value:?}");
                    }
                    out.push(']');
                }
                Object::Diagram(source) => {
                    let _ = write!(out, "[diagram {source:?}]");
                }
            }
            if let Some(link) = &item.style.link {
                let _ = write!(out, "{{link={:?}", link.href);
                if let Some(title) = &link.title {
                    let _ = write!(out, " title={title:?}");
                }
                out.push('}');
            }
        }
    }
}

fn dump_style(style: &Style, out: &mut String) {
    if *style == Style::default() {
        return;
    }
    let mut flags: Vec<String> = Vec::new();
    if style.bold {
        flags.push("bold".into());
    }
    if style.italic {
        flags.push("italic".into());
    }
    if style.underline {
        flags.push("underline".into());
    }
    if style.strike {
        flags.push("strike".into());
    }
    match style.vertical {
        Vertical::Baseline => {}
        Vertical::Super => flags.push("sup".into()),
        Vertical::Sub => flags.push("sub".into()),
    }
    match &style.font {
        None => {}
        Some(Font::Mono) => flags.push("mono".into()),
        Some(Font::Family(family)) => flags.push(format!("font={family}")),
    }
    if let Some(size) = style.size {
        flags.push(format!("size={}pt", size as f64 / 100.0));
    }
    if let Some(color) = &style.color {
        flags.push(format!("color={color}"));
    }
    if let Some(background) = &style.background {
        flags.push(format!("background={background}"));
    }
    if let Some(link) = &style.link {
        match &link.title {
            Some(title) => flags.push(format!("link={:?} title={title:?}", link.href)),
            None => flags.push(format!("link={:?}", link.href)),
        }
    }
    for extra in &style.extra {
        flags.push(extra.clone());
    }
    let _ = write!(out, "{{{}}}", flags.join(", "));
}
