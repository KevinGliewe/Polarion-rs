enum Piece {
    Char((char, Style)),
    Object(Object, Style),
}

/// The items of one line: whitespace collapsed and trimmed, no-break spaces as spaces.
fn line_items(segment: Vec<Atom>) -> Vec<Item> {
    let mut pieces: Vec<Piece> = Vec::new();
    // At the start of a line collapsible spaces disappear.
    let mut after_space = true;
    for atom in segment {
        match atom {
            Atom::Char {
                c: ' ',
                style,
                space: true,
            } => {
                if !after_space {
                    pieces.push(Piece::Char((' ', style)));
                    after_space = true;
                }
            }
            Atom::Char { c, style, .. } => {
                pieces.push(Piece::Char((c, style)));
                after_space = false;
            }
            Atom::Object(object, style) => {
                pieces.push(Piece::Object(object, style));
                after_space = false;
            }
            Atom::Br => {}
        }
    }
    while matches!(pieces.last(), Some(Piece::Char((c, _))) if *c == ' ' || *c == '\u{a0}') {
        pieces.pop();
    }
    let pieces = pieces
        .into_iter()
        .map(|piece| match piece {
            Piece::Char((c, _)) if c == ' ' || c == '\u{a0}' => {
                Piece::Char((' ', Style::default()))
            }
            piece => piece,
        })
        .collect();
    group(pieces)
}

/// Adjacent characters of one style as one text item.
fn group(pieces: Vec<Piece>) -> Vec<Item> {
    let mut items: Vec<Item> = Vec::new();
    for piece in pieces {
        match piece {
            Piece::Char((c, style)) => {
                let style = if c.is_whitespace() {
                    Style::default()
                } else {
                    style
                };
                if let Some(Item {
                    kind: ItemKind::Text(text),
                    style: last,
                }) = items.last_mut()
                    && *last == style
                {
                    text.push(c);
                    continue;
                }
                items.push(Item {
                    kind: ItemKind::Text(c.to_string()),
                    style,
                });
            }
            Piece::Object(object, style) => items.push(Item {
                kind: ItemKind::Object(object),
                style,
            }),
        }
    }
    items
}

/// A heading-like line's level, with bold and size removed from its items.
fn heading_line(mut items: Vec<Item>) -> (Option<u8>, Vec<Item>) {
    let visible: Vec<&Item> = items
        .iter()
        .filter(|item| match &item.kind {
            ItemKind::Text(t) => !t.trim().is_empty(),
            ItemKind::Object(_) => true,
        })
        .collect();
    if visible.is_empty() {
        return (None, items);
    }
    let size = |item: &Item| item.style.size.unwrap_or(1000);
    let heading = visible
        .iter()
        .all(|item| size(item) >= 1400 || (size(item) > 1000 && item.style.bold));
    if !heading {
        return (None, items);
    }
    let smallest = visible.iter().map(|item| size(item)).min().unwrap_or(1000);
    let level = match smallest {
        s if s >= 2200 => 1,
        s if s >= 1800 => 2,
        s if s >= 1400 => 3,
        s if s >= 1200 => 4,
        s if s >= 1100 => 5,
        _ => 6,
    };
    for item in &mut items {
        item.style.bold = false;
        item.style.size = None;
    }
    // Merging may now join neighbouring runs.
    let mut merged: Vec<Item> = Vec::new();
    for item in items {
        if let (
            Some(Item {
                kind: ItemKind::Text(text),
                style,
            }),
            ItemKind::Text(next),
        ) = (merged.last_mut(), &item.kind)
            && *style == item.style
        {
            text.push_str(next);
            continue;
        }
        merged.push(item);
    }
    (Some(level), merged)
}

