struct Cell {
    colspan: u32,
    rowspan: u32,
    background: Option<String>,
    rows: Vec<Row>,
}

#[derive(Debug, Clone, PartialEq)]
enum Row {
    Line(Line),
    /// An empty line box (a `<br>` on its own).
    Blank,
    /// A vertical margin of a block.
    Gap,
    /// Blank space of this many lines (after [`finish`]).
    Space(usize),
    Rule {
        indent: i64,
    },
    Table {
        indent: i64,
        rows: Vec<Vec<Cell>>,
    },
    Diagram {
        indent: i64,
        source: String,
    },
}

