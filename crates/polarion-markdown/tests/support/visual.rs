/// What an element inherits.
#[derive(Debug, Clone, Default)]
struct Ctx {
    style: Style,
    line: LineCtx,
    /// Lists the element is in (for the bullet shapes and list margins).
    lists: usize,
}

enum Atom {
    Char { c: char, style: Style, space: bool },
    Br,
    Object(Object, Style),
}

#[derive(Default)]
