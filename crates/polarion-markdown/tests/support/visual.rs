// Vertical space

#[derive(Clone, Copy, PartialEq)]
enum Edge {
    Document,
    Cell,
}

/// Blank lines and margins as [`Row::Space`]; a line holding only a diagram as the diagram.
fn finish(rows: Vec<Row>, edge: Edge) -> Vec<Row> {
    let mut out: Vec<Row> = Vec::new();
    let mut blanks = 0usize;
    let mut gap = false;
    let mut started = false;
    for row in rows {
        match row {
            Row::Blank => blanks += 1,
            Row::Gap => gap = true,
            row => {
                let space = if started && gap {
                    blanks.max(1)
                } else {
                    blanks
                };
                if space > 0 {
                    out.push(Row::Space(space));
                }
                blanks = 0;
                gap = false;
                started = true;
                out.push(match row {
                    Row::Line(line) if line.markers.is_empty() && line.items.len() == 1 => {
                        match &line.items[0].kind {
                            ItemKind::Object(Object::Diagram(source)) => Row::Diagram {
                                indent: line.ctx.indent,
                                source: source.clone(),
                            },
                            _ => Row::Line(line),
                        }
                    }
                    row => row,
                });
            }
        }
    }
    // Space at the end: invisible after the last line of the document; kept in a cell (it makes
    // the row taller), margins aside.
    if edge == Edge::Cell && blanks > 0 {
        out.push(Row::Space(blanks));
    }
    out
}

